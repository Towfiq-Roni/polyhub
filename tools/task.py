#!/usr/bin/env python3
"""Backlog CLI: one file per task (tasks/NNN-slug.md) + generated tasks/INDEX.md.

Usage: task.py show [id] | start <id> [--spec P] | log <id> "msg" | done <id> --gate-pass "note"
       | status <id> TODO|BLOCKED|FAILED "reason" | new "title" --goal G --prio 1|2|3 [--source S]
         [--trace E-NN/F-NN] [--deps 1,2] | index [--check] | brief
`start` sets the single focus (tasks/.focus); `done`/`status` on the focused task clear it.
Stdlib only. Frontmatter = flat `key: <JSON value>` lines (no YAML dependency).
"""
import datetime
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
TASKS = os.path.join(ROOT, "tasks")
INDEX = os.path.join(TASKS, "INDEX.md")
FOCUS = os.path.join(TASKS, ".focus")
KEYS = ["id", "title", "goal", "source", "priority", "status", "trace", "sprint",
        "deps", "build_spec", "started", "completed", "agents"]
SHORT = {"TODO": "todo", "IN_PROGRESS": "wip", "BLOCKED": "blk", "FAILED": "fail"}
HEADER = (
    "<!-- GENERATED by `python3 tools/task.py index` - do not edit by hand -->\n"
    "# Task index\n"
    "Open rows: id|status|prio|trace|title|deps   status: todo wip blk fail   "
    "prio: 1 urgent 2 soon 3 nice   deps: ids joined by +\n"
    "Done rows: id|trace|title\n"
    "Read ONLY the one task file you need: tasks/<id3>-<slug>.md. "
    "CLI: python3 tools/task.py show|start|log|done|status|new|index|brief\n"
)
USAGE = (
    'usage: task.py show [id] | start <id> [--spec P] | log <id> "msg" | '
    'done <id> --gate-pass "note" | status <id> TODO|BLOCKED|FAILED "reason" | '
    'new "title" --goal G --prio 1|2|3 [--source S] [--trace T] [--deps 1,2] | '
    "index [--check] | brief"
)
TEMPLATE = """# #{id} {title}

## Description / AC
Goal: {goal}. (add description + acceptance criteria)

## Build spec
- none yet

## Changelog
- {today} [new] created

## Completion notes
—
"""


def today():
    return datetime.date.today().isoformat()


def one_line(*vals):
    if any("\n" in v or "\r" in v for v in vals):
        die("single line only (no newline)\n" + USAGE)


def die(msg):
    print(msg, file=sys.stderr)
    sys.exit(1)


def parse(path):
    with open(path, encoding="utf-8") as f:
        lines = f.read().split("\n")
    if not lines or lines[0] != "---":
        raise ValueError("no frontmatter")
    try:
        end = lines.index("---", 1)
    except ValueError:
        raise ValueError("unterminated frontmatter")
    fm = {}
    for line in lines[1:end]:
        k, v = line.split(": ", 1)
        fm[k] = json.loads(v)
    return fm, "\n".join(lines[end + 1:])


def write(path, fm, body):
    out = "---\n" + "".join(
        "%s: %s\n" % (k, json.dumps(fm[k], ensure_ascii=False)) for k in KEYS) + "---\n" + body
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(out)
    os.replace(tmp, path)


def find(tid):
    try:
        n = int(tid)
    except ValueError:
        die("unknown task %s" % tid)
    hits = sorted(glob.glob(os.path.join(TASKS, "%03d-*.md" % n)))  # ponytail: first hit wins if duplicate ids exist -> fail on >1 hit
    if not hits:
        die("unknown task %s" % tid)
    return hits[0]


def load_all():
    """All parseable tasks sorted by id as (path, fm, body); corrupt files skipped with a warning."""
    rows = []
    for p in sorted(glob.glob(os.path.join(TASKS, "[0-9][0-9][0-9]-*.md"))):
        try:
            fm, body = parse(p)
            int(fm["id"])
            fm["title"], fm["status"]
            rows.append((p, fm, body))
        except Exception as e:  # noqa: BLE001 - one bad file must not break index/brief
            print("warning: skipping %s: %s" % (os.path.basename(p), e), file=sys.stderr)
    return sorted(rows, key=lambda r: int(r[1]["id"]))


def get_focus():
    try:
        with open(FOCUS, encoding="utf-8") as f:
            return int(f.read().strip())
    except (OSError, ValueError):
        return None


def set_focus(tid):
    # ponytail: focus is per working tree, parallel agents share it -> per-agent focus file if ever needed
    os.makedirs(TASKS, exist_ok=True)
    tmp = FOCUS + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("%d\n" % tid)
    os.replace(tmp, FOCUS)


def clear_focus_if(tid):
    if get_focus() == tid:
        try:
            os.remove(FOCUS)
        except OSError:
            pass


def clip(title, n):
    t = title.replace("|", "/")
    return t[:n] + "…" if len(t) > n else t


def build_index():
    op, dn = [], []
    for _, fm, _ in load_all():
        if fm["status"] == "DONE":
            dn.append("%d|%s|%s" % (fm["id"], fm.get("trace", ""), clip(fm["title"], 72)))
        else:
            op.append("%d|%s|%s|%s|%s|%s" % (
                fm["id"], SHORT.get(fm["status"], fm["status"].lower()), fm.get("priority", ""),
                fm.get("trace", ""), clip(fm["title"], 72), "+".join(str(d) for d in fm.get("deps", []))))
    return HEADER + "## Open\n" + "".join(r + "\n" for r in op) + "## Done\n" + "".join(r + "\n" for r in dn)


def reindex():
    os.makedirs(TASKS, exist_ok=True)
    tmp = INDEX + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(build_index())
    os.replace(tmp, INDEX)


def add_changelog(body, entry):
    """Append entry as last line of the ## Changelog section (before ## Completion notes)."""
    lines = body.split("\n")
    try:
        i = lines.index("## Completion notes")
    except ValueError:
        lines += ["", "## Completion notes", "—"]
        i = len(lines) - 2
    j = i
    while j > 0 and lines[j - 1].strip() == "":
        j -= 1
    lines.insert(j, entry)
    return "\n".join(lines)


def opts(args, flags):
    """Split args into (positionals, {--flag: value}); every flag in `flags` takes one value."""
    pos, o, i = [], {}, 0
    while i < len(args):
        a = args[i]
        if a in flags:
            if i + 1 >= len(args):
                die("%s needs a value\n%s" % (a, USAGE))
            o[a] = args[i + 1]
            i += 2
        elif a.startswith("--") and a != "--check":
            die("unknown option %s\n%s" % (a, USAGE))
        else:
            pos.append(a)
            i += 1
    return pos, o


def cmd_show(args):
    if not args:
        try:
            with open(INDEX, encoding="utf-8") as f:
                sys.stdout.write(f.read())
        except OSError:
            die("no tasks/INDEX.md: run python3 tools/task.py index")
        return
    with open(find(args[0]), encoding="utf-8") as f:
        sys.stdout.write(f.read())


def set_spec_section(body, spec):
    """Put spec path in the ## Build spec section: replace placeholder, skip if already listed."""
    lines = body.split("\n")
    try:
        i = lines.index("## Build spec")
    except ValueError:
        return body
    j = i + 1
    while j < len(lines) and not lines[j].startswith("## "):
        j += 1
    sec = lines[i + 1:j]
    if "- " + spec in sec:
        return body
    sec = [l for l in sec if l.strip() != "- none yet"]
    k = len(sec)
    while k > 0 and sec[k - 1].strip() == "":
        k -= 1
    sec.insert(k, "- " + spec)
    return "\n".join(lines[:i + 1] + sec + lines[j:])


# ponytail: read-modify-write is unlocked (concurrent log/start can lose an update; writes atomic via os.replace) -> flock if parallel agents write
# ponytail: done/status do not verify current status or gatekeeper PASS (honor system, enforced by process not code) -> check status/gate artifact if abused
def cmd_start(args):
    pos, o = opts(args, ["--spec"])
    if len(pos) != 1:
        die(USAGE)
    path = find(pos[0])
    fm, body = parse(path)
    if fm["status"] == "DONE":
        die("task %s is DONE" % pos[0])
    spec = o.get("--spec") or fm["build_spec"]
    if not spec or not os.path.isfile(os.path.join(ROOT, spec)):
        die("no build spec: run hub-planner first")
    tid, prev = int(fm["id"]), get_focus()
    if prev == tid and fm["status"] == "IN_PROGRESS" and spec == fm["build_spec"]:
        print("already focused")
        return
    fm["build_spec"] = spec
    body = set_spec_section(body, spec)
    if fm["status"] != "IN_PROGRESS":
        fm["status"] = "IN_PROGRESS"
        fm["started"] = fm["started"] or today()
    write(path, fm, add_changelog(
        body, "- %s [start] focus -> #%d, status IN_PROGRESS (spec %s)" % (today(), tid, spec)))
    if prev is not None and prev != tid:
        try:  # best-effort: missing/corrupt previous file is skipped, focus still moves
            pp = sorted(glob.glob(os.path.join(TASKS, "%03d-*.md" % prev)))[0]
            pfm, pbody = parse(pp)
            write(pp, pfm, add_changelog(pbody, "- %s [focus] focus moved to #%d" % (today(), tid)))
        except Exception:  # noqa: BLE001
            pass
    set_focus(tid)
    reindex()


def cmd_log(args):
    if len(args) != 2 or not args[1].strip():
        die(USAGE)
    one_line(args[1])
    path = find(args[0])
    fm, body = parse(path)
    write(path, fm, add_changelog(body, "- %s %s" % (today(), args[1].strip())))
    reindex()


def cmd_done(args):
    pos, o = opts(args, ["--gate-pass"])
    if len(pos) != 1 or not o.get("--gate-pass", "").strip():
        die("pass --gate-pass only after hub-gatekeeper PASS")
    note = o["--gate-pass"].strip()
    one_line(note)
    path = find(pos[0])
    fm, body = parse(path)
    fm["status"] = "DONE"
    fm["completed"] = today()
    body = add_changelog(body, "- %s [done] gatekeeper PASS" % today())
    head, sep, notes = body.partition("## Completion notes\n")
    if notes.strip() in ("", "—"):
        notes = note + "\n"
    else:
        notes = notes.rstrip("\n") + "\n%s %s\n" % (today(), note)
    write(path, fm, head + sep + notes)
    clear_focus_if(int(fm["id"]))
    reindex()


def cmd_status(args):
    if len(args) != 3 or args[1] not in ("TODO", "BLOCKED", "FAILED") or not args[2].strip():
        die(USAGE)
    one_line(args[2])
    path = find(args[0])
    fm, body = parse(path)
    fm["status"] = args[1]
    write(path, fm, add_changelog(body, "- %s [status] %s: %s" % (today(), args[1], args[2].strip())))
    clear_focus_if(int(fm["id"]))
    reindex()


def cmd_new(args):
    pos, o = opts(args, ["--goal", "--prio", "--source", "--trace", "--deps"])
    if len(pos) != 1 or not pos[0].strip() or "\n" in pos[0] or "\r" in pos[0]:
        die("title required, single line\n" + USAGE)
    if not o.get("--goal", "").strip():
        die("--goal required (every task cites a goal)")
    if o.get("--prio") not in ("1", "2", "3"):
        die("--prio required: 1|2|3")
    try:
        deps = [int(x) for x in o.get("--deps", "").split(",") if x.strip()]
    except ValueError:
        die("--deps must be comma-separated ids")
    title = pos[0].strip()
    ids = [int(os.path.basename(p)[:3]) for p in glob.glob(os.path.join(TASKS, "[0-9][0-9][0-9]-*.md"))]
    tid = max(ids, default=0) + 1
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower().replace("`", "")).strip("-")[:40].rstrip("-") or "task"
    os.makedirs(TASKS, exist_ok=True)
    path = os.path.join(TASKS, "%03d-%s.md" % (tid, slug))
    fm = {"id": tid, "title": title, "goal": o["--goal"].strip(),
          "source": o.get("--source", "Auto %s" % today()), "priority": int(o["--prio"]),
          "status": "TODO", "trace": o.get("--trace", ""), "sprint": "—", "deps": deps,
          "build_spec": "", "started": "", "completed": "", "agents": ""}
    write(path, fm, TEMPLATE.format(id=tid, title=title, goal=fm["goal"], today=today()))
    reindex()
    print(os.path.relpath(path, ROOT))


def cmd_index(args):
    if args == ["--check"]:
        try:
            with open(INDEX, encoding="utf-8") as f:
                cur = f.read()
        except OSError:
            cur = None
        if cur != build_index():
            die("INDEX.md stale: run python3 tools/task.py index")
        return
    if args:
        die(USAGE)
    reindex()


def cmd_brief(args):
    try:
        rows = load_all()
        foc = get_focus()
        cur = [fm for _, fm, _ in rows if fm["id"] == foc and fm["status"] == "IN_PROGRESS"]
        if cur:
            fm = cur[0]
            out = ["Focus: #%s [P%s] %s -- spec %s" % (
                fm["id"], fm.get("priority", "?"), fm["title"][:60], fm.get("build_spec", ""))]
        else:
            out = ["Focus: none -- python3 tools/task.py start <id> --spec <build-spec> before product edits"]
        todo = sorted((fm for _, fm, _ in rows if fm["status"] == "TODO"),
                      key=lambda fm: (fm.get("priority", 9), fm["id"]))[:3]
        out.append("Next: " + ("; ".join("#%s %s" % (fm["id"], fm["title"][:40]) for fm in todo) or "none"))
        print("\n".join(out))
    except Exception:  # noqa: BLE001 - session-start must never fail
        print("Focus: unknown\nNext: unknown")


CMDS = {"show": cmd_show, "start": cmd_start, "log": cmd_log, "done": cmd_done,
        "status": cmd_status, "new": cmd_new, "index": cmd_index, "brief": cmd_brief}


def main(argv):
    if not argv or argv[0] not in CMDS:
        die(USAGE)
    CMDS[argv[0]](argv[1:])


if __name__ == "__main__":
    main(sys.argv[1:])
